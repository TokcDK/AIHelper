using System;
using System.IO;
using AIHelper.Manage;
using NLog;

namespace AIHelper.Games
{
    /// <summary>
    /// The folder structure of a managed game: <c>Data</c> with the game itself,
    /// <c>Mods</c> with the mods of the user and <c>MO</c> with the Mod Organizer data of
    /// the game.
    /// </summary>
    /// <remarks>
    /// The game folder is always passed in rather than read from the current game, so the
    /// structure of every game can be completed while the list of games is built, before
    /// any of them is selected.
    /// </remarks>
    internal static class GameFolderLayout
    {
        static readonly Logger _log = LogManager.GetCurrentClassLogger();

        /// <summary>Name of the Mod Organizer profile every game starts with.</summary>
        internal const string DefaultProfileName = "Default";

        /// <summary>File of a Mod Organizer profile which lists the mods of the profile.</summary>
        internal const string ProfileModListFileName = "modlist.txt";

        private const string ModListHeader = "# This file was automatically generated by Mod Organizer.\r\n";
        private const string DownloadsDirName = "Downloads";
        private const string OverwriteDirName = "overwrite";

        /// <summary>
        /// Path of the exe a game is recognized by: its main exe in the data folder.
        /// </summary>
        /// <param name="game">game preset</param>
        /// <param name="gameDirPath">game folder</param>
        internal static string GetDataExePath(GameBase game, string gameDirPath)
        {
            return Path.Combine(gameDirPath, ManageSettings.DataDirName, game.GameExeName + ".exe");
        }

        /// <summary>true when the game can be recognized in the given folder.</summary>
        /// <param name="game">game preset</param>
        /// <param name="gameDirPath">folder which is expected to hold the game</param>
        internal static bool HasDataExe(GameBase game, string gameDirPath)
        {
            return File.Exists(GetDataExePath(game, gameDirPath));
        }

        /// <summary>true when the main exe is in the game folder itself.</summary>
        /// <param name="game">game preset</param>
        /// <param name="gameDirPath">game folder</param>
        internal static bool HasRootExe(GameBase game, string gameDirPath)
        {
            return File.Exists(Path.Combine(gameDirPath, game.GameExeName + ".exe"));
        }

        /// <summary>
        /// Creates the folders and files a managed game needs and points the Mod Organizer
        /// data of the game at them.
        /// </summary>
        /// <param name="gameDirPath">game folder</param>
        /// <param name="gameName">game name for the Mod Organizer ini</param>
        /// <param name="modOrganizerIniContent">
        /// content of a new ModOrganizer.ini. It is written only when the game has no ini
        /// yet, so the settings of a game which is managed already are kept.
        /// </param>
        /// <remarks>
        /// Nothing which exists is replaced: a game the user configured keeps its folders,
        /// its ini and its profiles, and only what is missing is created.
        /// </remarks>
        internal static void EnsureCreated(string gameDirPath, string gameName, string modOrganizerIniContent)
        {
            Directory.CreateDirectory(Path.Combine(gameDirPath, ManageSettings.DataDirName));
            Directory.CreateDirectory(Path.Combine(gameDirPath, ManageSettings.ModsDirName));
            Directory.CreateDirectory(Path.Combine(gameDirPath, DownloadsDirName));

            var modOrganizerDirPath = Path.Combine(gameDirPath, ManageSettings.AppModOrganizerDirName);
            Directory.CreateDirectory(modOrganizerDirPath);
            Directory.CreateDirectory(Path.Combine(modOrganizerDirPath, OverwriteDirName));
            Directory.CreateDirectory(Path.Combine(modOrganizerDirPath, ManageSettings.MoProfilesDirName, DefaultProfileName));

            CreateFileIfMissing(
                Path.Combine(modOrganizerDirPath, ManageSettings.MoCategoriesFileName),
                string.Empty);

            CreateFileIfMissing(
                Path.Combine(modOrganizerDirPath, ManageSettings.MoProfilesDirName, DefaultProfileName, ProfileModListFileName),
                ModListHeader);

            WriteModOrganizerIni(modOrganizerDirPath, gameDirPath, gameName, modOrganizerIniContent);
        }

        /// <summary>
        /// Moves the files of a game which is not unpacked yet into its data folder.
        /// </summary>
        /// <param name="gameDirPath">game folder</param>
        /// <remarks>
        /// The folders of the app itself are left where they are: <c>Mods</c> and <c>MO</c>
        /// are not part of the game, and moving them into <c>Data</c> would hide the mods
        /// of the user from the app and from Mod Organizer.
        /// </remarks>
        internal static void MoveGameFilesIntoDataFolder(string gameDirPath)
        {
            var dataDirPath = Path.Combine(gameDirPath, ManageSettings.DataDirName);
            Directory.CreateDirectory(dataDirPath);

            // the entries are materialised by GetDirectories and GetFiles, so the tree
            // which is walked is not the tree which is changed
            foreach (var dirPath in Directory.GetDirectories(gameDirPath))
            {
                TryMoveIntoDataFolder(dataDirPath, dirPath, true);
            }

            foreach (var filePath in Directory.GetFiles(gameDirPath))
            {
                TryMoveIntoDataFolder(dataDirPath, filePath, false);
            }
        }

        /// <summary>
        /// Writes the Mod Organizer ini of the game and points it at the folders of the
        /// game.
        /// </summary>
        private static void WriteModOrganizerIni(string modOrganizerDirPath, string gameDirPath, string gameName, string iniContent)
        {
            var iniPath = Path.Combine(modOrganizerDirPath, ManageSettings.MoIniFileName);
            if (File.Exists(iniPath))
            {
                return;
            }

            File.WriteAllText(iniPath, iniContent);

            var ini = ManageIni.GetINIFile(iniPath);

            // check mo ini game parameters exist
            ini.SetKey("General", "gameName", gameName);
            ini.SetKey("General", "gamePath", ToIniByteArrayValue(gameDirPath));
            ini.SetKey("General", "selected_profile", ToIniByteArrayValue(DefaultProfileName));
            ini.SetKey("Settings", "mod_directory", EscapeIniValue(Path.Combine(gameDirPath, ManageSettings.ModsDirName)));
            ini.SetKey("Settings", "download_directory", EscapeIniValue(Path.Combine(gameDirPath, DownloadsDirName)));
            ini.SetKey("Settings", "profiles_directory", EscapeIniValue(Path.Combine(modOrganizerDirPath, ManageSettings.MoProfilesDirName)));
            ini.SetKey("Settings", "overwrite_directory", EscapeIniValue(Path.Combine(modOrganizerDirPath, OverwriteDirName)));
        }

        /// <summary>
        /// Moves one entry of the game folder into the data folder of the game.
        /// </summary>
        /// <param name="dataDirPath">data folder of the game</param>
        /// <param name="sourcePath">folder or file to move</param>
        /// <param name="isDir">true for a folder</param>
        private static void TryMoveIntoDataFolder(string dataDirPath, string sourcePath, bool isDir)
        {
            string name = Path.GetFileName(sourcePath);
            if (isDir && IsAppFolderName(name))
            {
                return;
            }

            string targetPath = Path.Combine(dataDirPath, name);
            if (isDir ? Directory.Exists(targetPath) : File.Exists(targetPath))
            {
                // moving onto an existing entry would throw, and the game is used as it is
                _log.Warn("Not moved, the target exists already. Source=" + sourcePath + " Target=" + targetPath);
                return;
            }

            if (isDir)
            {
                Directory.Move(sourcePath, targetPath);
            }
            else
            {
                File.Move(sourcePath, targetPath);
            }
        }

        /// <summary>
        /// true for a folder name which belongs to the app rather than to the game.
        /// </summary>
        private static bool IsAppFolderName(string folderName)
        {
            return string.Equals(folderName, ManageSettings.DataDirName, StringComparison.OrdinalIgnoreCase)
                || string.Equals(folderName, ManageSettings.ModsDirName, StringComparison.OrdinalIgnoreCase)
                || string.Equals(folderName, ManageSettings.AppModOrganizerDirName, StringComparison.OrdinalIgnoreCase)
                || string.Equals(folderName, DownloadsDirName, StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>
        /// Writes a file with the given content, unless it exists already.
        /// </summary>
        private static void CreateFileIfMissing(string filePath, string content)
        {
            if (File.Exists(filePath))
            {
                return;
            }

            File.WriteAllText(filePath, content);
        }

        /// <summary>
        /// Mod Organizer stores a path with the backslashes escaped.
        /// </summary>
        private static string EscapeIniValue(string value)
        {
            return value.Replace("\\", "\\\\");
        }

        /// <summary>
        /// Mod Organizer stores a path of its general settings as a byte array.
        /// </summary>
        private static string ToIniByteArrayValue(string value)
        {
            return "@ByteArray(" + EscapeIniValue(value) + ")";
        }
    }
}
